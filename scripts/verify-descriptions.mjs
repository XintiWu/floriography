/**
 * 確認 flowerCatalog 已套用 cardDescriptions.json（同學文案）
 * 執行：node scripts/verify-descriptions.mjs
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const catalogPath = join(root, "src/data/flowerCatalog.json");
const curatedPath = join(root, "src/data/cardDescriptions.json");

if (!existsSync(catalogPath) || !existsSync(curatedPath)) {
  console.error("缺少 flowerCatalog.json 或 cardDescriptions.json");
  process.exit(1);
}

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const curated = JSON.parse(readFileSync(curatedPath, "utf8"));

let missing = 0;
let mismatch = 0;
let legacyMarkers = 0;

for (const card of catalog.cards) {
  const expected = curated[card.id];
  if (!expected?.trim()) {
    missing++;
    continue;
  }
  if (card.description !== expected) mismatch++;
  if (card.description?.includes("【手寫】") || card.description?.includes("# **第")) {
    legacyMarkers++;
  }
}

const ok = missing === 0 && mismatch === 0 && legacyMarkers === 0;
console.log({
  cards: catalog.cards.length,
  curatedEntries: Object.keys(curated).length,
  missingCurated: missing,
  descriptionMismatch: mismatch,
  legacyAutoGeneratedMarkers: legacyMarkers,
  status: ok ? "OK — 網站資料應顯示同學文案" : "NEEDS build:catalog",
});

process.exit(ok ? 0 : 1);
